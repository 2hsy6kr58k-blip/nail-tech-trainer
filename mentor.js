/**
 * התאמת כוונה מקומית לפי מילות מפתח.
 */
window.askMentor = function (question) {
  var q = (question || "").trim().toLowerCase();
  if (!q) {
    return { title: "שאלה ריקה", answer: "כתבי שאלה קצרה בעברית על טכניקת ציפורניים." };
  }
  var best = null;
  var bestScore = 0;
  (window.MentorKB || []).forEach(function (entry) {
    var score = 0;
    (entry.keys || []).forEach(function (k) {
      if (q.indexOf(String(k).toLowerCase()) !== -1) score += 1;
    });
    if (score > bestScore) {
      bestScore = score;
      best = entry;
    }
  });
  if (best && bestScore > 0) {
    return { title: best.title, answer: best.answer, matched: true };
  }
  return { title: "מנטורית", answer: window.MentorFallback, matched: false };
};

